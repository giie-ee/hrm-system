INSERT INTO work_policy_days (
    work_policy_id,
    day_of_week,
    is_working_day,
    start_time,
    end_time,
    expected_hours
)
SELECT wp.work_policy_id, schedule.day_of_week, schedule.is_working_day,
       schedule.start_time, schedule.end_time, schedule.expected_hours
FROM work_policies wp
CROSS JOIN (
    VALUES
        (0, FALSE, NULL::TIME, NULL::TIME, 0::NUMERIC),
        (1, TRUE,  '08:00'::TIME, '17:00'::TIME, 8::NUMERIC),
        (2, TRUE,  '08:00'::TIME, '17:00'::TIME, 8::NUMERIC),
        (3, TRUE,  '08:00'::TIME, '17:00'::TIME, 8::NUMERIC),
        (4, TRUE,  '08:00'::TIME, '17:00'::TIME, 8::NUMERIC),
        (5, TRUE,  '08:00'::TIME, '17:00'::TIME, 8::NUMERIC),
        (6, FALSE, NULL::TIME, NULL::TIME, 0::NUMERIC)
) AS schedule(day_of_week, is_working_day, start_time, end_time, expected_hours)
WHERE wp.policy_name = 'Default Work Schedule'
ON CONFLICT (work_policy_id, day_of_week) DO NOTHING;

