CREATE TABLE IF NOT EXISTS payroll_components (
    payroll_component_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_name VARCHAR(120) NOT NULL UNIQUE,
    component_type VARCHAR(20) NOT NULL CHECK (component_type IN ('Allowance', 'Deduction')),
    calculation_type VARCHAR(20) NOT NULL DEFAULT 'Fixed'
        CHECK (calculation_type IN ('Fixed', 'Percentage')),
    default_value NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (default_value >= 0),
    taxable BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS employee_payroll_components (
    employee_payroll_component_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id),
    payroll_component_id BIGINT NOT NULL REFERENCES payroll_components(payroll_component_id),
    component_value NUMERIC(12,2) NOT NULL CHECK (component_value >= 0),
    effective_from DATE NOT NULL,
    effective_to DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    created_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    UNIQUE (employee_id, payroll_component_id, effective_from)
);

CREATE INDEX IF NOT EXISTS idx_employee_payroll_components_active
    ON employee_payroll_components(employee_id, status, effective_from, effective_to);

