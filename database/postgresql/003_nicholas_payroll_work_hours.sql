  AND e.department_id IS NOT NULL;

-- Stable internal primary keys remain global. employee_number is the business-
-- facing identifier and can carry a department prefix without changing FKs.

CREATE TABLE IF NOT EXISTS work_policies (
    work_policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name VARCHAR(120) NOT NULL UNIQUE,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Africa/Lusaka',
    grace_minutes INTEGER NOT NULL DEFAULT 10 CHECK (grace_minutes BETWEEN 0 AND 180),
    early_departure_grace_minutes INTEGER NOT NULL DEFAULT 10
        CHECK (early_departure_grace_minutes BETWEEN 0 AND 180),
    minimum_half_day_hours NUMERIC(4,2) NOT NULL DEFAULT 4
        CHECK (minimum_half_day_hours BETWEEN 0 AND 24),
    status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    created_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_work_policies_single_active
    ON work_policies(status)
    WHERE status = 'Active';

CREATE TABLE IF NOT EXISTS work_policy_days (
    work_policy_day_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_policy_id BIGINT NOT NULL REFERENCES work_policies(work_policy_id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    is_working_day BOOLEAN NOT NULL DEFAULT TRUE,
    start_time TIME,
    end_time TIME,
    expected_hours NUMERIC(4,2) NOT NULL DEFAULT 0 CHECK (expected_hours BETWEEN 0 AND 24),
    UNIQUE (work_policy_id, day_of_week),
    CHECK (
        (is_working_day = FALSE AND start_time IS NULL AND end_time IS NULL AND expected_hours = 0)
        OR
        (is_working_day = TRUE AND start_time IS NOT NULL AND end_time IS NOT NULL
            AND end_time > start_time AND expected_hours > 0)
    )
);

