ALTER TABLE leave_types
    ADD COLUMN IF NOT EXISTS max_requests_per_year SMALLINT,
    ADD COLUMN IF NOT EXISTS max_consecutive_days SMALLINT,
    ADD COLUMN IF NOT EXISTS policy_notes TEXT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'leave_types_max_requests_per_year_check'
          AND conrelid = 'leave_types'::regclass
    ) THEN
        ALTER TABLE leave_types
            ADD CONSTRAINT leave_types_max_requests_per_year_check
            CHECK (max_requests_per_year IS NULL OR max_requests_per_year BETWEEN 1 AND 52);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'leave_types_max_consecutive_days_check'
          AND conrelid = 'leave_types'::regclass
    ) THEN
        ALTER TABLE leave_types
            ADD CONSTRAINT leave_types_max_consecutive_days_check
            CHECK (max_consecutive_days IS NULL OR max_consecutive_days BETWEEN 1 AND 366);
    END IF;
END $$;

