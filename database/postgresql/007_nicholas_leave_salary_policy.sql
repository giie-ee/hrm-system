CREATE TABLE IF NOT EXISTS position_salary_guidelines (
    salary_guideline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id BIGINT NOT NULL REFERENCES positions(position_id) ON DELETE CASCADE,
    recommended_basic_salary NUMERIC(12,2) NOT NULL CHECK (recommended_basic_salary > 0),
    currency CHAR(3) NOT NULL DEFAULT 'ZMW',
    effective_from DATE NOT NULL,
    effective_to DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (position_id, effective_from),
    CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

CREATE INDEX IF NOT EXISTS idx_position_salary_guidelines_position
    ON position_salary_guidelines(position_id, status, effective_from, effective_to);

CREATE UNIQUE INDEX IF NOT EXISTS uq_position_salary_guidelines_current
    ON position_salary_guidelines(position_id)
    WHERE status = 'Active' AND effective_to IS NULL;

